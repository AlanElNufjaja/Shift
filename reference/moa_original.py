def obtener_nombre_lugar(lat, lon):
    """Detecta la localidad, condado y estado a partir de las coordenadas."""
    try:
        url = f"https://nominatim.openstreetmap.org/reverse?format=json&lat={lat}&lon={lon}&zoom=10&addressdetails=1"
        headers = {"User-Agent": "FieldShift_NASA_SpaceApps/1.0"}
        r = requests.get(url, headers=headers, timeout=10).json()
        addr = r.get("address", {})
        localidad = addr.get("city") or addr.get("town") or addr.get("village") or addr.get("county") or "Zona Agrícola"
        condado = addr.get("county", "")
        estado = addr.get("state", "")
        pais = addr.get("country", "")
        return {
            "nombre_corto": f"Parcela en {localidad} ({estado})".strip(),
            "ubicacion_completa": r.get("display_name", f"Lat {lat}, Lon {lon}"),
            "condado": condado,
            "estado": estado,
            "pais": pais
        }
    except Exception:
        return {
            "nombre_corto": f"Parcela ({lat}, {lon})",
            "ubicacion_completa": f"Coordenadas: {lat}, {lon}",
            "condado": "N/D",
            "estado": "N/D",
            "pais": "N/D"
        }


def detectar_parcela_cercana(lat, lon):
    """Identifica si la coordenada pertenece a una de las 3 parcelas piloto o es un punto nuevo."""
    for pid, pinfo in PARCELAS_PILOTO.items():
        dist = math.hypot(lat - pinfo["lat"], lon - pinfo["lon"])
        if dist <= 0.15:
            return pid, pinfo
    return "custom-coord", PARCELAS_PILOTO["fresno-01"]


def obtener_suelo_usda(lat, lon, respaldo):
    """Consulta las propiedades del suelo en USDA SSURGO a partir de la coordenada."""
    min_lon, min_lat, max_lon, max_lat = lon - 0.01, lat - 0.01, lon + 0.01, lat + 0.01
    wkt_box = f"POLYGON(({min_lon} {min_lat}, {max_lon} {min_lat}, {max_lon} {max_lat}, {min_lon} {max_lat}, {min_lon} {min_lat}))"

    query = f"""
    SELECT TOP 1 m.mukey, m.muname, c.om_r, c.awc_r, c.kffact
    FROM mapunit m
    INNER JOIN component c ON m.mukey = c.mukey AND c.majcompflag = 'Yes'
    INNER JOIN mupolygon p ON m.mukey = p.mukey
    WHERE p.mupolygongeo.STIntersects(geometry::STGeomFromText('{wkt_box}', 4326)) = 1
    """
    try:
        resp = requests.post(
            "https://sdmdataaccess.sc.egov.usda.gov/Tabular/post.rest",
            json={"query": query, "format": "JSON"},
            timeout=15
        ).json()
        if "Table" in resp and len(resp["Table"]) > 0:
            f = resp["Table"][0]
            return {
                "mukey": str(f[0]),
                "textura": str(f[1]),
                "materia_organica_pct": round(float(f[2]), 2) if f[2] else respaldo["materia_organica_pct"],
                "retencion_agua_awc": round(float(f[3]), 2) if f[3] else respaldo["retencion_agua_awc"],
                "factor_erosion_k": round(float(f[4]), 2) if f[4] else respaldo["factor_erosion_k"]
            }
    except Exception:
        pass
    return respaldo


def generar_base_datos_por_coordenadas(lat, lon):
    """Recibe las variables de latitud y longitud y construye el JSON Maestro completo."""
    lugar = obtener_nombre_lugar(lat, lon)
    pid, info_base = detectar_parcela_cercana(lat, lon)
    nombre_parcela = info_base["nombre"] if pid != "custom-coord" else lugar["nombre_corto"]

    suelo = obtener_suelo_usda(lat, lon, info_base["suelo_respaldo"])

    url_nasa = (
        f"https://power.larc.nasa.gov/api/temporal/monthly/point"
        f"?parameters=T2M,T2M_MAX,T2M_MIN,PRECTOTCORR,GWETTOP"
        f"&community=AG&longitude={lon}&latitude={lat}"
        f"&start=2015&end=2024&format=JSON"
    )
    res_nasa = requests.get(url_nasa, timeout=20).json()["properties"]["parameter"]

    hist_cultivos = info_base["cultivos"]
    anios_lista = sorted(list(hist_cultivos.keys()))
    estado_por_anio = {}

    for idx, anio_str in enumerate(anios_lista):
        c_actual = hist_cultivos[anio_str]
        if c_actual == "Descanso":
            estado_por_anio[anio_str] = "Descanso / Fallow"
        elif idx >= 2 and hist_cultivos[anios_lista[idx-1]] == c_actual and hist_cultivos[anios_lista[idx-2]] == c_actual:
            estado_por_anio[anio_str] = "Monocultivo (3+ años)"
        elif idx >= 1 and hist_cultivos[anios_lista[idx-1]] == c_actual:
            estado_por_anio[anio_str] = "Monocultivo (2 años)"
        else:
            estado_por_anio[anio_str] = "Rotación"

    historial_unificado = []
    for anio in range(2015, 2025):
        anio_str = str(anio)
        cultivo_anio = hist_cultivos.get(anio_str, "Trigo")
        info_mercado = CATALOGO_PRECIOS[cultivo_anio]
        estado_suelo = estado_por_anio.get(anio_str, "Rotación")

        for m_num, nombre_mes in zip(MESES_KEYS, MESES_NOMBRES):
            clave = f"{anio}{m_num}"
            t_max = res_nasa["T2M_MAX"].get(clave, -999)
            t_min = res_nasa["T2M_MIN"].get(clave, -999)
            lluvia = res_nasa["PRECTOTCORR"].get(clave, -999)
            humedad = res_nasa["GWETTOP"].get(clave, -999)

            historial_unificado.append({
                "anio": anio,
                "mes": nombre_mes,
                "fecha": f"{anio}-{m_num}",
                "temp_max_c": round(t_max, 1) if t_max != -999 else 25.0,
                "lluvia_mm": round(lluvia * 30, 1) if lluvia != -999 else 0.0,
                "riesgo_helada": bool(t_min <= 2.5) if t_min != -999 else False,
                "humedad_suelo_pct": round(humedad * 100, 1) if humedad != -999 else 15.0,
                "cultivo_principal": cultivo_anio,
                "codigo_cdl": info_mercado["codigo_cdl"],
                "estado_suelo": estado_suelo,
                "precio_usd_ton": info_mercado["precio_usd_ton"]
            })

    return {
        "parcelas": {
            pid: {
                "nombre": nombre_parcela,
                "coordenadas": {"lat": lat, "lon": lon},
                "ubicacion_detectada": lugar,
                "propiedades_suelo": suelo,
                "historial_unificado": historial_unificado
            }
        },
        "precios_mercado": CATALOGO_PRECIOS
    }


json_maestro_salida = generar_base_datos_por_coordenadas(lat_frontend, lon_frontend)

